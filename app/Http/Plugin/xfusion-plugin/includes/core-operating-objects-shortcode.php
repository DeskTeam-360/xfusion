/** Slug of the company the menu should point at ('' when unknown). */
function xfusion_core_objects_company_slug(): string
{
    $route = $GLOBALS['xfusion_route_company'] ?? null;
    if (is_array($route) && ! empty($route['slug'])) {
        return (string) $route['slug'];
    }

    if (! is_user_logged_in() || ! function_exists('xfusion_wp_user_linked_company_id') || ! function_exists('xfusion_company_slug_by_id')) {
        return '';
    }

    return xfusion_company_slug_by_id(xfusion_wp_user_linked_company_id(get_current_user_id()));
}

